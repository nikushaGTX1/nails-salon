export const dictionaries = { en, ka, ru };

@Injectable({ providedIn: 'root' })
export class TranslationService {
  readonly language = signal<Language>(this.initialLanguage());
  constructor(
    @Inject(DOCUMENT) private readonly document: Document,
    private readonly site: SiteContentService,
  ) {
    this.updateDocument(this.language());
  }
  t(key: string): string {
    return (
      this.site.content().translations[this.language()]?.[key] ??
      dictionaries[this.language()][key] ??
      en[key] ??
      key
    );
  }
  setLanguage(language: Language): void {
    this.language.set(language);
    localStorage.setItem('nailbar-language', language);
    this.updateDocument(language);
  }
  private initialLanguage(): Language {
    const saved = localStorage.getItem('nailbar-language');
    if (saved === 'en' || saved === 'ka' || saved === 'ru') return saved;
    const browser = navigator.language.toLowerCase();
    return browser.startsWith('ka') ? 'ka' : browser.startsWith('ru') ? 'ru' : 'en';
  }
  private updateDocument(language: Language): void {
    this.document.documentElement.lang = language;
  }
}
